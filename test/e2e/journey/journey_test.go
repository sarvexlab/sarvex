// Package journey_test contains end-to-end tests covering the full merchant
// journey from WooCommerce store creation through to serving agents via UCP.
//
// The test exercises all three planes in-process:
//   - Control plane (HTTP API)
//   - Sync plane (background workers via Redis event bus)
//   - Serving plane (profile served via /connector/profile)
//
// External dependencies:
//   - MongoDB (from MONGO_URI env var)
//   - Redis (from REDIS_ADDR env var, default localhost:6379)
//   - WooCommerce store: provided by wcMock (in-process, no Docker needed)
package journey_test

import (
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// testHMACSecret is the HMAC shared secret injected for E2E pairing tests.
// In production this is generated by the platform and delivered via QR code / config.
var testHMACSecret = []byte("e2e-test-hmac-secret-32-bytes-ok")

// TestJourney_WooCommerceToAgentServing tests the complete merchant journey:
//
//  1. Operator provisions merchant + invites owner + creates store
//  2. Merchant begins pairing; plugin completes pairing with WC credentials
//  3. Plugin sends product signals; sync plane ingests catalog
//  4. Readiness scoring shows issues (missing description, non-standard attributes)
//  5. Operator (or merchant) applies remediations; write-backs reach WC mock
//  6. Re-score shows improved readiness
//  7. UCP profile is served via GET /connector/profile (HMAC)
func TestJourney_WooCommerceToAgentServing(t *testing.T) {
	// ── Setup: start the WooCommerce mock ────────────────────────────────────
	wc := newWCMock()
	defer wc.Close()

	// ── Stage 1: Operator provisions merchant ────────────────────────────────
	t.Log("Stage 1: operator provisions merchant, member, store")

	merchantID := operatorCreateMerchant(t, "E2E Test Merchant")
	require.NotEmpty(t, merchantID)
	t.Logf("  merchant_id: %s", merchantID)

	operatorInviteMember(t, merchantID, "owner@e2etest.example.com")

	storeID := operatorCreateStore(t, merchantID, "E2E WooCommerce Store", "woocommerce")
	require.NotEmpty(t, storeID)
	t.Logf("  store_id: %s", storeID)

	// Operator board should now list this merchant.
	resp := apiGet(t, "/v1/operator/merchants", "operator-token")
	var merchants map[string]any
	decodeJSON(t, resp, 200, &merchants)
	require.NotNil(t, merchants["data"])

	// ── Stage 2: Pairing ─────────────────────────────────────────────────────
	t.Log("Stage 2: begin pairing, inject HMAC secret, plugin completes pairing")

	connectorID, pairingCode := beginPairing(t, merchantID, storeID)
	t.Logf("  connector_id: %s pairing_code: %s", connectorID, pairingCode)

	// Inject HMAC secret so the plugin can sign its completePairing call.
	injectHMACSecret(t, connectorID, testHMACSecret)

	// Plugin completes pairing with WC store credentials pointing at the mock.
	creds := storeCredentials(wc.URL(), merchantID)
	completePairing(t, connectorID, storeID, pairingCode, testHMACSecret, creds)

	// Connector should now be healthy.
	waitUntil(t, 5*time.Second, "connector healthy", func() bool {
		return connectorIsHealthy(t, merchantID, connectorID)
	})
	t.Log("  connector is healthy")

	// ── Stage 3: Catalog sync ─────────────────────────────────────────────────
	t.Log("Stage 3: plugin sends product signals; sync plane ingests catalog")

	// The plugin sends a signal for each product on the initial sync.
	for _, entityID := range []string{"WIDGET-001", "GADGET-002", "DEVICE-003"} {
		sendSignal(t, connectorID, storeID, testHMACSecret, entityID, "product")
		// Small delay to avoid sequence collisions (sequence is time-based in helpers).
		time.Sleep(5 * time.Millisecond)
	}

	// Wait for the sync plane to process signals and score products.
	// The sync plane picks up events from Redis Streams asynchronously.
	waitUntil(t, 30*time.Second, "catalog scored (product count > 0)", func() bool {
		_, ok := getReadiness(t, merchantID, storeID)
		return ok
	})
	t.Log("  catalog scoring completed")

	// Also trigger a resync to pull all products (initial sync flow).
	operatorResync(t, merchantID, connectorID)

	// ── Stage 4: Readiness shows issues ──────────────────────────────────────
	t.Log("Stage 4: verify readiness issues present (missing description, attribute quality)")

	// Wait for scoring to reflect ingested products.
	waitUntil(t, 30*time.Second, "readiness score available", func() bool {
		score, ok := getReadiness(t, merchantID, storeID)
		return ok && score >= 0
	})

	score, _ := getReadiness(t, merchantID, storeID)
	t.Logf("  initial overall readiness score: %d", score)
	// Score should be less than perfect due to WIDGET-001 missing description
	// and GADGET-002 non-standard attributes.

	// ── Stage 5: Remediation ─────────────────────────────────────────────────
	t.Log("Stage 5: list and apply remediations")

	// Poll for remediations to be available (depends on scoring being done).
	var remediations []map[string]any
	waitUntil(t, 30*time.Second, "remediations available", func() bool {
		remediations = listRemediations(t, merchantID, storeID)
		return len(remediations) > 0
	})
	t.Logf("  found %d remediations", len(remediations))

	// Apply all available remediations.
	remIDs := make([]string, 0, len(remediations))
	for _, r := range remediations {
		if id, ok := r["remediation_id"].(string); ok {
			remIDs = append(remIDs, id)
		}
	}
	require.NotEmpty(t, remIDs, "must have remediation IDs to apply")

	result := applyRemediations(t, merchantID, storeID, remIDs)
	t.Logf("  applied: %v, write_back_ids: %v", result["applied"], result["write_back_ids"])

	// Verify write-backs reached the WooCommerce mock. Of everything listed,
	// only the title normalization is a rule-based fix with a path to the store
	// (WooCommerce "name"); the rest — description, stock, shipping data — need
	// the merchant, so applying them must leave the store alone.
	waitUntil(t, 15*time.Second, "write-backs received by WC mock", func() bool {
		return len(wc.WriteBacks()) > 0
	})
	wbs := wc.WriteBacks()
	t.Logf("  WC mock received %d write-back(s)", len(wbs))
	require.Len(t, wbs, 1, "only the rule-based title fix may be written to the store")
	assert.Equal(t, 1001, wbs[0].ProductID, "the fix is for WIDGET-001")
	assert.Equal(t, map[string]any{"name": "E2E Test Widget"}, wbs[0].Fields, "the normalized title, under WooCommerce's own field name")
	widget, ok := wc.Product(1001)
	require.True(t, ok)
	assert.Equal(t, "E2E Test Widget", widget.Name)

	// ── Stage 6: Re-score after remediation ──────────────────────────────────
	t.Log("Stage 6: send re-sync signals, verify score improves")

	// Re-send signals so the sync plane re-ingests the now-patched products.
	for _, entityID := range []string{"WIDGET-001", "GADGET-002"} {
		sendSignal(t, connectorID, storeID, testHMACSecret, entityID, "product")
		time.Sleep(5 * time.Millisecond)
	}

	// Score should improve or stay the same (never regress after remediation).
	time.Sleep(2 * time.Second) // brief wait for re-scoring
	newScore, _ := getReadiness(t, merchantID, storeID)
	t.Logf("  post-remediation readiness score: %d (was: %d)", newScore, score)

	// ── Stage 7: Profile served ───────────────────────────────────────────────
	t.Log("Stage 7: UCP profile served via /connector/profile")

	profileBody, statusCode := fetchProfile(t, connectorID, storeID, testHMACSecret)
	t.Logf("  profile HTTP status: %d", statusCode)

	switch statusCode {
	case 200:
		t.Logf("  profile body length: %d bytes", len(profileBody))
		assert.NotEmpty(t, profileBody, "a 200 is served verbatim at /.well-known/ucp, so it must carry the profile")
	case 409:
		// No serving snapshot built yet: the contract's "no servable profile
		// yet" — the plugin keeps its last-known-good copy.
		t.Log("  no servable profile yet (409) — valid for a brand-new store")
	default:
		t.Errorf("profile fetch: status %d, want 200 with a profile or 409 (sarvex-v1-control-plane.yaml)", statusCode)
	}

	t.Log("Journey completed: merchant provisioned → paired → catalog synced → remediated → profile served")
}

// TestJourney_OperatorProvisioning verifies the operator provisioning endpoints
// introduced in the bootstrap sequence (architecture §3 Domain 1).
func TestJourney_OperatorProvisioning(t *testing.T) {
	// Create merchant
	merchantID := operatorCreateMerchant(t, "Provisioning Test Merchant")
	require.NotEmpty(t, merchantID)

	// Invite two members
	operatorInviteMember(t, merchantID, "owner1@test.example.com")
	operatorInviteMember(t, merchantID, "owner2@test.example.com")

	// Create two stores (architecture §2a: model must allow many stores per merchant)
	storeID1 := operatorCreateStore(t, merchantID, "Store One", "woocommerce")
	storeID2 := operatorCreateStore(t, merchantID, "Store Two", "woocommerce")
	require.NotEmpty(t, storeID1)
	require.NotEmpty(t, storeID2)
	assert.NotEqual(t, storeID1, storeID2, "stores must have distinct IDs")

	// List merchants as operator
	resp := apiGet(t, "/v1/operator/merchants", "operator-token")
	var merchantList map[string]any
	decodeJSON(t, resp, 200, &merchantList)
	data, ok := merchantList["data"].([]any)
	require.True(t, ok, "data should be an array")
	require.NotEmpty(t, data)

	// Merchant can list their own stores
	resp = apiGet(t, "/v1/stores", merchantToken(merchantID))
	var storeList map[string]any
	decodeJSON(t, resp, 200, &storeList)
	storeData, ok := storeList["data"].([]any)
	require.True(t, ok)
	assert.GreaterOrEqual(t, len(storeData), 2, "merchant should see both stores")

	// Non-operator cannot call operator endpoints
	resp = apiGet(t, "/v1/operator/merchants", merchantToken(merchantID))
	assert.Equal(t, 403, resp.StatusCode, "non-operator should be forbidden")
	resp.Body.Close()
}

// TestJourney_TenantIsolation verifies that merchant A cannot see or modify merchant B's data.
func TestJourney_TenantIsolation(t *testing.T) {
	// Provision two independent merchants.
	merchantA := operatorCreateMerchant(t, "Tenant Isolation Merchant A")
	merchantB := operatorCreateMerchant(t, "Tenant Isolation Merchant B")

	storeA := operatorCreateStore(t, merchantA, "Store A", "woocommerce")
	storeB := operatorCreateStore(t, merchantB, "Store B", "woocommerce")

	// Merchant A cannot access merchant B's store.
	resp := apiGet(t, "/v1/stores/"+storeB, merchantToken(merchantA))
	assert.Equal(t, 404, resp.StatusCode, "merchant A should get 404 for merchant B's store")
	resp.Body.Close()

	// Merchant B cannot initiate pairing on merchant A's store.
	resp = apiPost(t, "/v1/stores/"+storeA+"/connectors/pairing", merchantToken(merchantB), map[string]any{
		"platform": "woocommerce",
	})
	assert.Equal(t, 404, resp.StatusCode, "merchant B should get 404 trying to pair merchant A's store")
	resp.Body.Close()

	// Merchant A can see their own store.
	resp = apiGet(t, "/v1/stores/"+storeA, merchantToken(merchantA))
	assert.Equal(t, 200, resp.StatusCode, "merchant A should see their own store")
	resp.Body.Close()
}

// TestJourney_PairingHMACVerification verifies that the pairing HMAC check rejects
// invalid signatures.
func TestJourney_PairingHMACVerification(t *testing.T) {
	merchantID := operatorCreateMerchant(t, "HMAC Verification Merchant")
	storeID := operatorCreateStore(t, merchantID, "HMAC Verification Store", "woocommerce")

	connectorID, pairingCode := beginPairing(t, merchantID, storeID)

	// Inject the real secret.
	realSecret := []byte("real-hmac-secret-32-bytes-padding")
	injectHMACSecret(t, connectorID, realSecret)

	// Attempt to complete pairing with a wrong secret — must be rejected.
	wrongSecret := []byte("wrong-hmac-secret-32-bytes-padding")
	creds := storeCredentials("http://localhost:9999", merchantID)

	body := map[string]any{
		"connector_id":      connectorID,
		"pairing_code":      pairingCode,
		"store_credentials": creds,
	}

	// We call hmacSignedRequest with the wrong key; the server should reject.
	resp := hmacSignedRequest(t, "POST", "/v1/connectors/pairing/complete", storeID+":"+connectorID, wrongSecret, body, nil)
	assert.Equal(t, 401, resp.StatusCode, "wrong HMAC should be rejected as unauthorized")
	resp.Body.Close()

	// With the correct key it should succeed.
	completePairing(t, connectorID, storeID, pairingCode, realSecret, creds)
}
