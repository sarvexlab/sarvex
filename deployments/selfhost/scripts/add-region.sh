#!/usr/bin/env bash
# add-region.sh <provider-label> <ssh-host> <region> <origin-public-ip> <core-leafnode-url>
#
#   add-region.sh hetzner root@203.0.113.9 eu-west 203.0.113.9 \
#       nats-leaf://core.sarvex.internal:7422
#
# The entire day-N+1 runbook (plan §6) as one command: provision a node on
# ANY provider, bootstrap it as an edge k3s cluster, join its NATS to the
# core supercluster, register the serving+gateway Helm releases with Argo
# CD via a git push, and add the new origin to the Cloudflare pool. No
# console — Cloudflare's, Argo CD's, or otherwise — at any point.
#
# Prerequisite: KUBECONFIG for the new region's cluster must be reachable
# under the name printed by provision-node.sh before step 3 runs — export
# KUBECONFIG=./kubeconfig-<region>.yaml before invoking this script, or
# pass it via --kubeconfig (see below).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
source lib.sh

PROVIDER="${1:?usage: add-region.sh <provider-label> <ssh-host> <region> <origin-public-ip> <core-leafnode-url>}"
HOST="${2:?ssh-host required}"
REGION="${3:?region required}"
ORIGIN_IP="${4:?origin public IP required (what Cloudflare's pool points at)}"
CORE_LEAF_URL="${5:?core leafnode URL required, e.g. nats-leaf://core.sarvex.internal:7422}"

require_cmd jq git terraform
[ -n "${KUBECONFIG:-}" ] || fail "export KUBECONFIG to a kubeconfig for the NEW region's cluster before running this (provision-node.sh's step 1 output explains how to fetch one)"

echo "════ add-region: $REGION on $PROVIDER ════════════════════════════"

echo "── 1/5 Provisioning node ────────────────────────────────────────"
./provision-node.sh "$HOST" agent "${K3S_URL:?set K3S_URL=https://<core-node-ip>:6443 first}" "${K3S_TOKEN:?set K3S_TOKEN (from the core server's /var/lib/rancher/k3s/server/node-token) first}"
# Note: edge nodes join as k3s AGENTS of the core server's control plane by
# default (simplest topology for a single-node edge). If a region needs its
# own independent k3s control plane instead, run provision-node.sh with
# role=server --cluster-init and adjust KUBECONFIG accordingly before
# continuing from step 2.

echo "── 2/5 Bootstrapping cluster (Cilium, Gateway API, regional Redis) ─"
./bootstrap-cluster.sh "$REGION" edge

echo "── 3/5 Joining NATS leaf node to core supercluster ──────────────"
./bootstrap-nats-leaf.sh "$REGION" "$CORE_LEAF_URL"

echo "── 4/5 Writing Helm values + Argo CD Application manifests ──────"
HELM_DIR="$SELFHOST_DIR/helm/sarvex-serving"
GATEWAY_DIR="$SELFHOST_DIR/helm/sarvex-gateway"
APPS_DIR="$SELFHOST_DIR/gitops/apps"

cat > "$HELM_DIR/values-${REGION}.yaml" <<EOF
# Generated by add-region.sh for region '$REGION' on $PROVIDER — edit
# resources/hostnames as needed, but redis/nats addresses are wired to this
# region's own local instances (see bootstrap-cluster.sh / bootstrap-nats-leaf.sh).
replicaCount: 1
resources:
  requests: { cpu: 250m, memory: 256Mi }
  limits: { memory: 512Mi }
redis:
  address: "redis.sarvex-${REGION}.svc.cluster.local:6379"
nats:
  url: "nats://nats-leaf.sarvex-${REGION}.svc.cluster.local:4222"
vault:
  address: "http://vault.sarvex-core.svc.cluster.local:8200" # edge regions still authenticate to the CORE Vault for secrets — see plan's Vault Agent Injector note
routing:
  hostnames: ["ucp-${REGION}.\${ROOT_DOMAIN:-sarvex.example}"]
EOF

cat > "$GATEWAY_DIR/values-${REGION}.yaml" <<EOF
core: false
hostnames:
  serving: ["ucp-${REGION}.\${ROOT_DOMAIN:-sarvex.example}"]
EOF

cat > "$APPS_DIR/sarvex-serving-${REGION}.yaml" <<EOF
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: sarvex-serving-${REGION}
  namespace: argocd
spec:
  project: default
  source:
    repoURL: https://github.com/sarvexlab/sarvex.cp
    targetRevision: main
    path: deployments/selfhost/helm/sarvex-serving
    helm:
      valueFiles: [values-${REGION}.yaml]
  destination:
    server: ${ARGOCD_CLUSTER_SERVER_URL:?set ARGOCD_CLUSTER_SERVER_URL to this new cluster's API server URL as registered with 'argocd cluster add'}
    namespace: sarvex-${REGION}
  syncPolicy:
    automated: { prune: true, selfHeal: true }
    syncOptions: [CreateNamespace=true]
EOF

cat > "$APPS_DIR/sarvex-gateway-${REGION}.yaml" <<EOF
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: sarvex-gateway-${REGION}
  namespace: argocd
spec:
  project: default
  source:
    repoURL: https://github.com/sarvexlab/sarvex.cp
    targetRevision: main
    path: deployments/selfhost/helm/sarvex-gateway
    helm:
      valueFiles: [values-${REGION}.yaml]
  destination:
    server: ${ARGOCD_CLUSTER_SERVER_URL}
    namespace: sarvex-${REGION}
  syncPolicy:
    automated: { prune: true, selfHeal: true }
    syncOptions: [CreateNamespace=true]
EOF

require_cmd argocd
argocd cluster add "$(kubectl config current-context)" --yes >/dev/null || log "argocd cluster add reported an issue — check manually if this region's Application stays Unknown"

log "committing new region manifests to git..."
git -C "$ROOT_DIR" add \
	"$HELM_DIR/values-${REGION}.yaml" \
	"$GATEWAY_DIR/values-${REGION}.yaml" \
	"$APPS_DIR/sarvex-serving-${REGION}.yaml" \
	"$APPS_DIR/sarvex-gateway-${REGION}.yaml"
git -C "$ROOT_DIR" commit -m "selfhost: add region ${REGION} (${PROVIDER})"
git -C "$ROOT_DIR" push
ok "pushed — Argo CD (already watching this repo since bootstrap-argocd.sh) will reconcile the new region automatically"

echo "── 5/5 Adding origin to the Cloudflare pool ──────────────────────"
TFVARS="$SELFHOST_DIR/terraform/cloudflare/regions.auto.tfvars.json"
jq --arg region "$REGION" --arg ip "$ORIGIN_IP" \
	'.regions[$region] = {"origin_address": $ip, "is_primary": false}' \
	"$TFVARS" > "${TFVARS}.tmp" && mv "${TFVARS}.tmp" "$TFVARS"

(
	cd "$SELFHOST_DIR/terraform/cloudflare"
	terraform init -input=false >/dev/null
	terraform plan -out=tfplan
	terraform apply -input=false tfplan
)
ok "Cloudflare pool now includes '$REGION' — proximity steering will start routing nearby traffic there"

echo "════ region '$REGION' is live — zero dashboard clicks ════════════"
