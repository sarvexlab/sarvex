// SyncedArtifactReader reads the artifact records the sync plane writes for a
// surface (sync_surface_artifacts). It is read-only: the sync plane is the
// collection's one writer (CLAUDE.md §2.1), and this package reads it by name
// without importing sync code.
//
// Every surface whose artifact is generated by its sync-plane half uses this
// one reader through NewSyncedArtifact / NewSyncedSignal, so a new surface
// needs no reader of its own.
type SyncedArtifactReader interface {
	// Get returns the record, or (nil, nil) when none has been generated yet —
	// a normal pre-enrollment condition.
	Get(ctx context.Context, merchantID domain.MerchantID, storeID domain.StoreID, surfaceID, artifactID string) (*surfaces.ArtifactRecord, error)
}

type mongoSyncedArtifacts struct{ col *mongo.Collection }

// NewMongoSyncedArtifactReader reads sync_surface_artifacts.
func NewMongoSyncedArtifactReader(db *mongo.Database) SyncedArtifactReader {
	return &mongoSyncedArtifacts{col: db.Collection(surfaces.CollectionArtifacts)}
}

func (r *mongoSyncedArtifacts) Get(ctx context.Context, merchantID domain.MerchantID, storeID domain.StoreID, surfaceID, artifactID string) (*surfaces.ArtifactRecord, error) {
	// Query-level tenant fence: both ids are in the filter (ADR-2).
	var rec surfaces.ArtifactRecord
	err := r.col.FindOne(ctx, bson.M{
		"merchant_id": string(merchantID),
		"store_id":    string(storeID),
		"surface_id":  surfaceID,
		"artifact_id": artifactID,
	}).Decode(&rec)
	if errors.Is(err, mongo.ErrNoDocuments) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read surface artifact: %w", err)
	}
	return &rec, nil
}

// syncedArtifact is an ArtifactProvider over a sync-generated record.
type syncedArtifact struct {
	surfaceID, artifactID, labelKey string
	reader                          SyncedArtifactReader
}

// NewSyncedArtifact returns the ArtifactProvider for an artifact the surface's
// sync-plane half generates. labelKey is the console's vue-i18n key.
func NewSyncedArtifact(surfaceID, artifactID, labelKey string, reader SyncedArtifactReader) ArtifactProvider {
	return &syncedArtifact{surfaceID: surfaceID, artifactID: artifactID, labelKey: labelKey, reader: reader}
}

func (a *syncedArtifact) ID() string { return a.artifactID }

func (a *syncedArtifact) Artifact(ctx context.Context, cc CheckContext) (*domain.SurfaceArtifact, error) {
	rec, err := a.reader.Get(ctx, cc.MerchantID, cc.StoreID, a.surfaceID, a.artifactID)
	if err != nil || rec == nil || rec.GeneratedAt == nil {
		return nil, err
	}
	detail := make(map[string]string, len(rec.Detail)+1)
	for k, v := range rec.Detail {
		detail[k] = v
	}
	if rec.LastFetchedAt != nil {
		detail["last_fetched_at"] = rec.LastFetchedAt.UTC().Format("2006-01-02T15:04:05Z")
	}
	return &domain.SurfaceArtifact{
		LabelKey:    a.labelKey,
		URL:         rec.URL,
		Detail:      detail,
		GeneratedAt: rec.GeneratedAt,
	}, nil
}

// syncedSignal is a VerificationSignal over a signal the sync plane observed.
type syncedSignal struct {
	id, surfaceID, artifactID string
	signal                    surfaces.Signal
	reader                    SyncedArtifactReader
}

// NewSyncedSignal returns a VerificationSignal that is true once the sync
// plane has observed signal on the surface's artifact.
func NewSyncedSignal(id, surfaceID, artifactID string, signal surfaces.Signal, reader SyncedArtifactReader) VerificationSignal {
	return &syncedSignal{id: id, surfaceID: surfaceID, artifactID: artifactID, signal: signal, reader: reader}
}

func (s *syncedSignal) ID() string { return s.id }

func (s *syncedSignal) Verified(ctx context.Context, cc CheckContext) (bool, error) {
	rec, err := s.reader.Get(ctx, cc.MerchantID, cc.StoreID, s.surfaceID, s.artifactID)
	if err != nil || rec == nil {
		return false, err
	}
	return rec.Observed(s.signal), nil
}

// ArtifactCheck is a PrerequisiteCheck helper: it passes once a sync-generated
// artifact exists. labelKey/remediationKey are console vue-i18n keys.
type artifactExistsCheck struct {
	id, surfaceID, artifactID, labelKey, remediationKey string
	reader                                              SyncedArtifactReader
}

// NewArtifactExistsCheck returns a check that passes once the surface's
// sync-plane half has generated artifactID for the store.
func NewArtifactExistsCheck(id, surfaceID, artifactID, labelKey, remediationKey string, reader SyncedArtifactReader) PrerequisiteCheck {
	return &artifactExistsCheck{id: id, surfaceID: surfaceID, artifactID: artifactID, labelKey: labelKey, remediationKey: remediationKey, reader: reader}
}

func (c *artifactExistsCheck) ID() string { return c.id }

func (c *artifactExistsCheck) Evaluate(ctx context.Context, cc CheckContext) domain.PrerequisiteResult {
	res := domain.PrerequisiteResult{LabelKey: c.labelKey, RemediationKey: c.remediationKey}
	rec, err := c.reader.Get(ctx, cc.MerchantID, cc.StoreID, c.surfaceID, c.artifactID)
	if err != nil || rec == nil || rec.GeneratedAt == nil {
		res.Reason = "not generated yet"
		return res
	}
	res.Passed = true
	res.RemediationKey = ""
	return res
}
